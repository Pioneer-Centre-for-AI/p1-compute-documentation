<h1>Terms and Conditions</h1>

<h2>Access and Responsibility</h2>

<p>
  P1 does not directly operate the compute resources, as these are managed by the respective
  institutions. However, P1 provides guidance and support for using these resources and works
  closely with the institutions to ensure they meet the needs of P1-affiliated researchers.
</p>

<h3>Access Eligibility</h3>

<p>
  P1 HPC resources are intended for academic research purposes only and are available exclusively
  to researchers at Danish universities. Industry access is generally prohibited unless it is part
  of a research collaboration with a Danish university.
</p>

<p>
  If you are not affiliated with a Danish university but are working on a project with a
  university-affiliated researcher, we can create an additional guest agreement covering data
  privacy and security to grant you access to these resources.
</p>

<h2>User Revision Policy</h2>

<p>
  User review happens once or twice a year. We cannot rely on personal email addresses for this
  process, so we use emails managed by partner institutions to verify user activity.
</p>

<p>During each review, users receive an email asking them to:</p>

<ul>
  <li>Confirm they are still actively using the cluster (no response may indicate that the partner university has revoked access)</li>
  <li>Provide a brief explanation of their current research activities</li>
</ul>

<p>The HPC governance board receives a list of all current accounts so they can step in for manual review if needed.</p>

<p>Users who either fail to respond or are not approved by the governance board will have their account placed in a 6-month grace period.</p>

<h2>Data Retention Policy</h2>

<p>
  Once an account enters the grace period, the user's data is moved to a temporary storage
  location, where it will remain for the duration of the grace period (6 months, until the next
  review cycle). This allows for recovery or changes in data ownership. The user can at any time
  request to have their data deleted.
</p>

<p><strong>Data Recovery Process:</strong></p>

<ul>
  <li>Users can request data recovery during the grace period by contacting the HPC governance board</li>
  <li>Data ownership can be transferred to another approved user during this time</li>
  <li>After the grace period ends, all data in temporary storage will be permanently deleted</li>
</ul>

<p>
  <strong>Important:</strong> Users should ensure they have backed up any important data before or during
  the grace period, as data recovery after the grace period is not possible.
</p>
